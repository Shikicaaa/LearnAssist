def quiz_params(request: QuizRequest) -> dict:
    """What the user asked for, in a canonical, JSON-friendly form. It is stored with the quiz
    and is all the worker needs to rebuild the same selection of material."""
    return {
        "topic": request.topic or None,
        "source_ids": sorted({str(source_id) for source_id in request.source_ids}),
        "num_questions": request.num_questions,
        "difficulty": request.difficulty,
        "types": sorted(set(request.types)),
        "script": request.script,
    }


def _is_usable(artifact: Artifact) -> bool:
    """Ready, or still being generated by a worker that is presumably alive."""
    if artifact.status == ArtifactStatus.READY:
        return True
    if artifact.status == ArtifactStatus.PENDING:
        timeout = timedelta(minutes=get_settings().quiz_pending_timeout_minutes)
        return artifact.updated_at > utcnow() - timeout
    return False


def create_quiz(
    db: Session,
    *,
    user_id: uuid.UUID,
    session: SessionOut,
    request: QuizRequest,
    embedder: Embedder,
    llm: LLMProvider,
    queue: TaskQueue,
) -> Artifact:
    """Returns the quiz for this request: a stored one if the same request was made before on
    the same material, otherwise a new `pending` one that a worker is asked to generate.

    A stored quiz costs nothing, so it is returned before the rate limit and the per-session
    quota are looked at: those protect the model, not the cache.
    """
    settings = get_settings()
    if request.num_questions > settings.quiz_max_questions:
        raise BadRequestError(f"At most {settings.quiz_max_questions} questions per quiz.")

    params = quiz_params(request)
    source_ids = [uuid.UUID(source_id) for source_id in params["source_ids"]]
    chunks = select_material(
        db,
        embedder=embedder,
        user_id=user_id,
        session_id=session.id,
        topic=params["topic"],
        source_ids=source_ids,
    )
    if not chunks:
        raise BadRequestError(
            "There is no material to build a quiz from. Add sources or pick another topic."
        )

    key = ArtifactKey(
        session_id=session.id,
        kind=KIND_QUIZ,
        params_hash=params_hash(
            topic=params["topic"],
            source_ids=source_ids,
            num_questions=params["num_questions"],
            difficulty=params["difficulty"],
            types=params["types"],
            script=params["script"],
        ),
        context_hash=context_hash([chunk.text for chunk in chunks]),
        prompt_version=QUIZ_PROMPT_VERSION,
        llm_model=llm.model,
    )
    repo = ArtifactRepository(db)
    # Without `regenerate` the request always maps to variant 0; with it, to the next free one.
    variant = repo.next_variant(key) if request.regenerate else 0
    existing = repo.find(key, variant)
    if existing is not None and _is_usable(existing):
        return existing

    # From here on a model call is needed.
    enforce_rate_limit(f"rl:quiz:{user_id}", settings.quiz_requests_per_hour, 3600)
    if repo.count_active(session.id, user_id, KIND_QUIZ) >= settings.quiz_max_per_session:
        raise QuotaExceededError(
            f"This session already has {settings.quiz_max_per_session} quizzes. "
            "Delete one to make room for a new one."
        )

    if existing is None:
        artifact, created = repo.claim(key, variant=variant, user_id=user_id, params=params)
        if not created and _is_usable(artifact):
            return artifact  # lost a race: an identical request is already being served
    else:
        artifact = existing  # failed or abandoned: try again
    artifact.status = ArtifactStatus.PENDING.value
    artifact.error = None
    artifact.updated_at = utcnow()
    db.commit()  # the worker must see the row before it is asked to work on it

    queue.enqueue(QUIZ_TASK, {"artifact_id": str(artifact.id)})
    db.refresh(artifact)  # with an inline queue the task has already finished
    return artifact


def get_artifact(db: Session, user_id: uuid.UUID, artifact_id: uuid.UUID) -> Artifact:
    artifact = ArtifactRepository(db).get_owned(artifact_id, user_id)
    if artifact is None:
        raise NotFoundError("Artifact not found.")
    return artifact


def list_artifacts(
    db: Session, user_id: uuid.UUID, session_id: uuid.UUID, limit: int, offset: int
) -> tuple[list[Artifact], int]:
    return ArtifactRepository(db).list_for_session(session_id, user_id, limit, offset)


def delete_artifact(db: Session, user_id: uuid.UUID, artifact_id: uuid.UUID) -> None:
    repo = ArtifactRepository(db)
    repo.delete(get_artifact(db, user_id, artifact_id))
    db.commit()
